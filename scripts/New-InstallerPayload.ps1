#Requires -Version 5.1
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$RuntimeDirectory,
    [Parameter(Mandatory)][string]$OutputHeader,
    [string]$ConfigurationDirectory,
    [string]$SupportDirectory,
    [string]$LicensePath,
    [string]$RuntimeManifestPath,
    [string]$OutputManifest,
    [switch]$AllowUnsignedDevelopment
)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'Build-Provenance.ps1')
$runtime = Assert-LakeSafePath (Resolve-Path -LiteralPath $RuntimeDirectory).Path
if (!$RuntimeManifestPath) { $RuntimeManifestPath = Join-Path $runtime 'BUILD-PROVENANCE.json' }
$provenance = Read-LakeJson $RuntimeManifestPath
Assert-LakeBuildDocument $provenance -RequireTests -AllowUnsignedDevelopment:$AllowUnsignedDevelopment
if ($provenance.Component -cne 'Runtime' -or $provenance.Configuration -cne 'Release' -or $provenance.Profiling) {
    throw 'Installer payload requires a tested, non-profiling Release runtime.'
}
$runtimeHash = (Get-LakeFileRecord $RuntimeManifestPath 'runtime-manifest').Sha256
if (!$ConfigurationDirectory) { $ConfigurationDirectory = $runtime }
if (!$SupportDirectory) { $SupportDirectory = $runtime }
if (!$LicensePath) { $LicensePath = Join-Path $runtime 'LICENSE' }
$records = @(
    @{Name='LakeWindowedLauncher.exe';Path=(Join-Path $runtime 'LakeWindowedLauncher.exe')},
    @{Name='LakeWindowedFix.dll';Path=(Join-Path $runtime 'LakeWindowedFix.dll')},
    @{Name='LakeWindowedFix.ini';Path=(Join-Path $ConfigurationDirectory 'LakeWindowedFix.ini')},
    @{Name='LICENSE';Path=$LicensePath},
    @{Name='Measure-LakeResources.ps1';Path=(Join-Path $SupportDirectory 'Measure-LakeResources.ps1')},
    @{Name='LakeResourceMetrics.psm1';Path=(Join-Path $SupportDirectory 'LakeResourceMetrics.psm1')}
)
$output = Assert-LakeSafePath $OutputHeader
if (!$OutputManifest) { $OutputManifest = $output+'.manifest.json' }
$manifestPath = Assert-LakeSafePath $OutputManifest
if ($manifestPath -ieq $output -or $manifestPath -ieq [IO.Path]::GetFullPath($RuntimeManifestPath)) { throw 'Payload outputs must not overwrite an input.' }
$marker = '// Generated by New-InstallerPayload.ps1; MIT project files only.'
if ((Test-Path -LiteralPath $output) -and !([IO.File]::ReadAllText($output).StartsWith($marker))) {
    throw 'OutputHeader already exists and is not an owned generated header.'
}
if (Test-Path -LiteralPath $manifestPath) {
    $previous = Read-LakeJson $manifestPath
    Assert-LakePayloadDocument $previous
    if (!(Test-Path -LiteralPath $output) -or (Get-LakeFileRecord $output 'header').Sha256 -cne $previous.HeaderSha256) {
        throw 'Modified/unpaired payload outputs preserved.'
    }
} elseif (Test-Path -LiteralPath $output) {
    throw 'Existing payload header has no paired manifest; preserve it and use a fresh build directory.'
}
foreach ($record in $records) {
    $item = Get-LakeSafeFile $record.Path 16777216
    $record.Bytes = [IO.File]::ReadAllBytes($item.FullName)
    $sha = [Security.Cryptography.SHA256]::Create()
    try { $record.Sha256 = ([BitConverter]::ToString($sha.ComputeHash($record.Bytes))).Replace('-','').ToLowerInvariant() }
    finally { $sha.Dispose() }
    if ($record.Name -match '\.(exe|dll)$') {
        $bytes = $record.Bytes
        if ($bytes.Length -lt 64 -or [BitConverter]::ToUInt16($bytes,0) -ne 0x5A4D) { throw 'Runtime must contain Windows x86 PE binaries.' }
        $pe = [BitConverter]::ToInt32($bytes,60)
        if ($pe -lt 64 -or $pe -gt $bytes.Length-6 -or [BitConverter]::ToUInt32($bytes,$pe) -ne 0x4550 -or [BitConverter]::ToUInt16($bytes,$pe+4) -ne 0x14c) { throw 'Runtime must contain Windows x86 PE binaries.' }
    }
}
$payloadFiles = @($records | ForEach-Object { [pscustomobject]@{Name=$_.Name;Sha256=$_.Sha256;Bytes=$_.Bytes.Length} })
Assert-LakeSameRecords $payloadFiles $provenance.Files 'payload/runtime'
# Also validate the runtime directory when CMake supplies support/config paths:
# overrides may not silently mix new defaults with previously tested binaries.
Assert-LakeSameRecords @(Get-LakeArtifactRecords $runtime @(Get-LakeRuntimeNames)) $provenance.Files 'runtime provenance'
[IO.Directory]::CreateDirectory((Split-Path $output -Parent)) | Out-Null
$temporary = $output+'.'+[guid]::NewGuid().ToString('N')+'.tmp'
$writer = [IO.StreamWriter]::new($temporary,$false,[Text.Encoding]::ASCII)
try {
    $writer.WriteLine($marker)
    $writer.WriteLine('// Runtime build: '+$provenance.BuildId+'; manifest SHA256: '+$runtimeHash)
    $writer.WriteLine('#pragma once')
    $writer.WriteLine('#include "setup_engine.h"')
    $writer.WriteLine('namespace lakefix::setup {')
    for ($i=0; $i -lt $records.Count; $i++) {
        $writer.WriteLine("inline constexpr unsigned char kPayload$i[] = {")
        $bytes = $records[$i].Bytes
        for ($offset=0; $offset -lt $bytes.Length; $offset+=32) {
            $last = [Math]::Min($offset+31,$bytes.Length-1)
            $values = for ($j=$offset; $j -le $last; $j++) { '0x{0:x2}' -f $bytes[$j] }
            $writer.WriteLine('    '+($values -join ',')+',')
        }
        $writer.WriteLine('};')
    }
    $writer.WriteLine('inline const PayloadFile kPayloadFiles[] = {')
    for ($i=0; $i -lt $records.Count; $i++) {
        $record = $records[$i]
        $writer.WriteLine(('    {{L"{0}", kPayload{1}, sizeof(kPayload{1}), L"{2}"}},' -f $record.Name,$i,$record.Sha256))
    }
    $writer.WriteLine('};')
    $writer.WriteLine('} // namespace lakefix::setup')
} finally { $writer.Dispose() }
$payload = [pscustomobject][ordered]@{
    Schema=1;Project='lake-controller-windowed-fix';Kind='InstallerPayload'
    RuntimeBuildId=$provenance.BuildId;RuntimeManifestSha256=$runtimeHash
    Version=$provenance.Version;SourceCommit=$provenance.SourceCommit;SourceDirty=$provenance.SourceDirty
    SourceFingerprint=$provenance.SourceFingerprint;AbiVersion=$provenance.AbiVersion;ConfigSchema=$provenance.ConfigSchema
    Architecture=$provenance.Architecture
    Configuration=$provenance.Configuration;Profiling=$provenance.Profiling;DistributionProfile=$provenance.DistributionProfile
    Files=$payloadFiles;HeaderSha256=(Get-LakeFileRecord $temporary 'header').Sha256
}
if (Test-Path -LiteralPath $output) { [IO.File]::Replace($temporary,$output,[NullString]::Value) }
else { [IO.File]::Move($temporary,$output) }
# A crash between header/manifest writes fails closed: setup finalization checks
# both hashes. These are build intermediates, never public release assets.
Write-LakeJson $manifestPath $payload
Write-Host 'Generated installer payload: six MIT files; no proprietary components.'
Write-Host "Payload provenance: $manifestPath"
